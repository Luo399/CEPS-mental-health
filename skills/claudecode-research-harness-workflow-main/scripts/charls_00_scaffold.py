import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from _charls_utils import get_logger, INTER_DIR, PROC_DIR, LOG_DIR, REPORTS_DIR

log = get_logger("charls_scaffold", "charls_00_scaffold.log")


def main():
    for d in [INTER_DIR, PROC_DIR, LOG_DIR, REPORTS_DIR]:
        d.mkdir(parents=True, exist_ok=True)
        log.info("DIR OK: %s", d.relative_to(d.parent.parent))

    merge_report = REPORTS_DIR / "charls_merge_report.md"
    if not merge_report.exists():
        merge_report.write_text(
            "# CHARLS Merge Report\n\n"
            "> Auto-generated by charls_00_scaffold.py. Each merge step appends a section.\n\n",
            encoding="utf-8",
        )
        log.info("CREATED reports/charls_merge_report.md")
    else:
        log.info("EXISTS reports/charls_merge_report.md (cleared for fresh run)")
        merge_report.write_text(
            "# CHARLS Merge Report\n\n"
            "> Auto-generated by charls_00_scaffold.py. Each merge step appends a section.\n\n",
            encoding="utf-8",
        )

    log.info("SUCCESS")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        log.exception("FATAL: %s", exc)
        sys.exit(1)
